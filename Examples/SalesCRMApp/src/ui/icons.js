const SVG_NS = 'http://www.w3.org/2000/svg';
const TAG_RE = /<(path|rect|circle)\s+([^>]+?)\s*\/>/g;
const ATTR_RE = /([a-zA-Z-]+)="([^"]*)"/g;

export function icon(name, size = 16) {
  const s = Math.max(8, Math.min(64, Math.round(Number(size) || 16)));
  const svg = document.createElementNS(SVG_NS, 'svg');
  svg.setAttribute('width', String(s));
  svg.setAttribute('height', String(s));
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('fill', 'none');
  svg.setAttribute('stroke', 'currentColor');
  svg.setAttribute('stroke-width', '1.8');
  svg.setAttribute('stroke-linecap', 'round');
  svg.setAttribute('stroke-linejoin', 'round');
  svg.setAttribute('aria-hidden', 'true');

  const body = PATHS[name] || PATHS.fileText;
  for (const m of body.matchAll(TAG_RE)) {
    const child = document.createElementNS(SVG_NS, m[1]);
    for (const a of m[2].matchAll(ATTR_RE)) {
      child.setAttribute(a[1], a[2]);
    }
    svg.appendChild(child);
  }
  return svg;
}
